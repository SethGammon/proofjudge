import { createHash, createPrivateKey, createPublicKey, generateKeyPairSync } from "node:crypto";
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const envFiles = [".env.deploy", ".env.research", ".env.negotiation", ".env.governance"];
const primaryEnv = path.join(root, envFiles[0]);

function readEnvValue(file, key) {
  if (!existsSync(file)) return undefined;
  const match = readFileSync(file, "utf8").match(new RegExp(`^${key}=(.+)$`, "m"));
  return match?.[1]?.trim();
}

function upsertEnvValue(contents, key, value) {
  const line = `${key}=${value}`;
  const pattern = new RegExp(`^${key}=.*$`, "m");
  if (pattern.test(contents)) return contents.replace(pattern, line);
  return `${contents.trimEnd()}\n${line}\n`;
}

let privateKeyValue = process.argv.includes("--rotate")
  ? undefined
  : readEnvValue(primaryEnv, "PROOFJUDGE_ED25519_PRIVATE_KEY");

if (!privateKeyValue) {
  const { privateKey } = generateKeyPairSync("ed25519");
  privateKeyValue = privateKey.export({ format: "der", type: "pkcs8" }).toString("base64");
}

const privateKey = createPrivateKey({
  key: Buffer.from(privateKeyValue, "base64"),
  format: "der",
  type: "pkcs8"
});
const publicKeyValue = createPublicKey(privateKey).export({ format: "der", type: "spki" }).toString("base64");
const keyId = `ed25519:${createHash("sha256").update(publicKeyValue).digest("hex")}`;

for (const relativePath of envFiles) {
  const file = path.join(root, relativePath);
  if (!existsSync(file)) throw new Error(`Missing deployment environment file: ${relativePath}`);
  let contents = readFileSync(file, "utf8");
  contents = upsertEnvValue(contents, "PROOFJUDGE_ED25519_PUBLIC_KEY", publicKeyValue);
  contents = upsertEnvValue(contents, "PROOFJUDGE_ED25519_PRIVATE_KEY", privateKeyValue);
  writeFileSync(file, contents, { encoding: "utf8", mode: 0o600 });
  try { chmodSync(file, 0o600); } catch { /* Windows does not expose POSIX modes. */ }
}

const trustedFile = path.join(root, "src", "trusted-signing-keys.ts");
const existing = existsSync(trustedFile) ? readFileSync(trustedFile, "utf8") : "";
const existingKeys = [...existing.matchAll(/\"([A-Za-z0-9+/=]{40,200})\"/g)].map((match) => match[1]);
const keys = [...new Set([...existingKeys, publicKeyValue])];
const generated = [
  "// Generated by scripts/provision-signing-key.mjs. Public keys are safe to publish.",
  "// Every value is a base64-encoded Ed25519 SubjectPublicKeyInfo DER document.",
  "export const trustedEd25519PublicKeys: readonly string[] = [",
  ...keys.map((key) => `  \"${key}\",`),
  "];",
  ""
].join("\n");
writeFileSync(trustedFile, generated, "utf8");

console.log(`Provisioned ProofJudge signer ${keyId}`);
console.log(`Published public key: ${publicKeyValue}`);
